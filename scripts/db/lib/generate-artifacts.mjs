#!/usr/bin/env node
// Generates portable database artifacts from a Postgres catalog. pnpm db:sync calls it with an
// in-memory database built from supabase/migrations (scripts/db/lib/offline-db.mjs); the CLI entry
// point below also accepts any Postgres URL:
//   db/schema/schema.dbml                        engine-neutral model (dbdiagram.io, @dbml/cli)
//   db/schema/portable/{mysql,sqlserver,sqlite}.sql   starting-point DDL for other SQL services
//   db/export/queries/NNN_<schema>.<table>.sql   one explicit, portable SELECT per table, FK load order
//   db/export/manifest.json                      load order, columns, source types, portable types
//   db/portability/supabase-dependencies.md      inventory of Supabase-specific constructs in use
// Usage: pnpm db:sync   (or: node scripts/db/lib/generate-artifacts.mjs --db-url <url> [--root <dir>])
// Owner: database-architect. Output is deterministic so CI can detect drift.
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

// Schemas managed by the Supabase platform (same list the Supabase CLI excludes from db dump).
export const MANAGED_SCHEMAS = [
  'information_schema', '_analytics', '_realtime', '_supavisor', 'auth', 'etl', 'extensions', 'pgbouncer',
  'realtime', 'storage', 'supabase_functions', 'supabase_migrations', 'cron', 'dbdev', 'graphql',
  'graphql_public', 'net', 'pgmq', 'pgsodium', 'pgsodium_masks', 'pgtle', 'repack', 'tiger', 'tiger_data',
  'topology', 'vault',
];
const MANAGED_REGEX = `^(${MANAGED_SCHEMAS.join('|')}|pg_.*|timescaledb_.*|_timescaledb_.*)$`;
const HEADER = 'GENERATED by pnpm db:sync from supabase/migrations. Do not edit.';

function cliArgs() {
  const a = process.argv.slice(2);
  const get = (name) => {
    const i = a.indexOf(name);
    return i >= 0 ? a[i + 1] : undefined;
  };
  const here = path.dirname(fileURLToPath(import.meta.url));
  return { dbUrl: get('--db-url') ?? process.env.HARNESS_DB_URL, root: path.resolve(get('--root') ?? path.join(here, '..', '..', '..')) };
}

function supabaseBin(root) {
  const local = path.join(root, 'node_modules', '.bin', process.platform === 'win32' ? 'supabase.cmd' : 'supabase');
  return fs.existsSync(local) ? [local] : ['npx', '-y', 'supabase'];
}

// Runs SQL through the Supabase CLI (`supabase db query --db-url`) against any Postgres URL.
// Returns the rows as objects. pnpm db:sync uses an in-process runner instead.
export function makeRunner(root, dbUrl) {
  const [bin, ...pre] = supabaseBin(root);
  return function query(sql) {
    const tmp = path.join(os.tmpdir(), `harness-q-${process.pid}-${Math.random().toString(36).slice(2)}.sql`);
    fs.writeFileSync(tmp, sql, 'utf8');
    try {
      const target = dbUrl ? ['--db-url', dbUrl] : ['--local'];
      const res = spawnSync(bin, [...pre, 'db', 'query', ...target, '-o', 'json', '-f', tmp], {
        cwd: root,
        encoding: 'utf8',
        maxBuffer: 512 * 1024 * 1024,
      });
      const outText = res.stdout ?? '';
      const start = outText.indexOf('{');
      if (res.status !== 0 || start < 0) {
        throw new Error(`supabase db query failed: ${(res.stderr || outText).trim().split('\n').slice(-5).join(' ')}`);
      }
      const parsed = JSON.parse(outText.slice(start));
      if (parsed._tag === 'Error') throw new Error(parsed.error?.message ?? 'query error');
      return parsed.rows ?? [];
    } finally {
      fs.rmSync(tmp, { force: true });
    }
  };
}

const qi = (id) => `"${String(id).replace(/"/g, '""')}"`;
const yes = (v) => v === true || v === 't' || v === 'true';
const parseJson = (v) => (v === null || v === undefined ? [] : typeof v === 'string' ? JSON.parse(v) : v);

export async function loadCatalog(query) {
  const tables = (await query(`
    select n.nspname as schema, c.relname as name,
      coalesce(obj_description(c.oid, 'pg_class'), '') as comment,
      c.relrowsecurity as rls,
      (select json_agg(json_build_object(
          'name', a.attname,
          'type', format_type(a.atttypid, a.atttypmod),
          'base', case when t.typtype = 'd' then format_type(t.typbasetype, t.typtypmod) else null end,
          'category', t.typcategory::text,
          'typtype', t.typtype::text,
          'typeSchema', tn.nspname,
          'typeName', t.typname,
          'notNull', a.attnotnull,
          'identity', a.attidentity::text,
          'generated', a.attgenerated::text,
          'default', pg_get_expr(ad.adbin, ad.adrelid)
        ) order by a.attnum)::text
        from pg_attribute a
        join pg_type t on t.oid = a.atttypid
        join pg_namespace tn on tn.oid = t.typnamespace
        left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
        where a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped) as columns,
      (select json_agg(att.attname order by k.ord)::text
        from pg_constraint pk
        cross join lateral unnest(pk.conkey) with ordinality as k(attnum, ord)
        join pg_attribute att on att.attrelid = pk.conrelid and att.attnum = k.attnum
        where pk.conrelid = c.oid and pk.contype = 'p') as pk,
      (select json_agg(json_build_object(
          'name', fk.conname,
          'refSchema', rn.nspname,
          'refTable', rc.relname,
          'columns', (select json_agg(a2.attname order by kk.ord) from unnest(fk.conkey) with ordinality as kk(attnum, ord)
                      join pg_attribute a2 on a2.attrelid = fk.conrelid and a2.attnum = kk.attnum),
          'refColumns', (select json_agg(a3.attname order by kk2.ord) from unnest(fk.confkey) with ordinality as kk2(attnum, ord)
                      join pg_attribute a3 on a3.attrelid = fk.confrelid and a3.attnum = kk2.attnum),
          'refTypes', (select json_agg(format_type(a4.atttypid, a4.atttypmod) order by kk3.ord) from unnest(fk.confkey) with ordinality as kk3(attnum, ord)
                      join pg_attribute a4 on a4.attrelid = fk.confrelid and a4.attnum = kk3.attnum),
          'onDelete', fk.confdeltype::text,
          'onUpdate', fk.confupdtype::text
        ) order by fk.conname)::text
        from pg_constraint fk
        join pg_class rc on rc.oid = fk.confrelid
        join pg_namespace rn on rn.oid = rc.relnamespace
        where fk.conrelid = c.oid and fk.contype = 'f') as fks
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
    where c.relkind in ('r', 'p') and not c.relispartition and n.nspname !~ '${MANAGED_REGEX}'
    order by n.nspname, c.relname`)).map((t) => ({
    schema: t.schema,
    name: t.name,
    comment: t.comment ?? '',
    rls: yes(t.rls),
    columns: parseJson(t.columns),
    pk: parseJson(t.pk),
    fks: parseJson(t.fks),
    indexes: [],
  }));

  const indexes = await query(`
    select n.nspname as schema, t.relname as table, i.relname as name, ix.indisunique as is_unique,
      (select json_agg(a.attname order by k.ord) from unnest(ix.indkey::int2[]) with ordinality as k(attnum, ord)
         join pg_attribute a on a.attrelid = t.oid and a.attnum = k.attnum)::text as columns,
      (ix.indexprs is not null or ix.indpred is not null) as special,
      pg_get_indexdef(ix.indexrelid) as def
    from pg_index ix
    join pg_class i on i.oid = ix.indexrelid
    join pg_class t on t.oid = ix.indrelid
    join pg_namespace n on n.oid = t.relnamespace
    where not ix.indisprimary and t.relkind in ('r', 'p') and n.nspname !~ '${MANAGED_REGEX}'
    order by 1, 2, 3`);
  const byKey = new Map(tables.map((t) => [`${t.schema}.${t.name}`, t]));
  for (const ix of indexes) {
    byKey.get(`${ix.schema}.${ix.table}`)?.indexes.push({ name: ix.name, unique: yes(ix.is_unique), columns: parseJson(ix.columns), special: yes(ix.special), def: ix.def });
  }

  const enums = (await query(`
    select n.nspname as schema, t.typname as name, json_agg(e.enumlabel order by e.enumsortorder)::text as labels
    from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
    where n.nspname !~ '${MANAGED_REGEX}'
    group by 1, 2 order by 1, 2`)).map((e) => ({ schema: e.schema, name: e.name, labels: parseJson(e.labels) }));
  return { tables, enums };
}

// Kahn topological sort on FK dependencies (self references ignored, cycles broken by name).
export function loadOrder(tables) {
  const key = (s, n) => `${s}.${n}`;
  const known = new Set(tables.map((t) => key(t.schema, t.name)));
  const deps = new Map(
    tables.map((t) => [
      key(t.schema, t.name),
      new Set(t.fks.map((f) => key(f.refSchema, f.refTable)).filter((k) => k !== key(t.schema, t.name) && known.has(k))),
    ]),
  );
  const order = [];
  const cycles = [];
  const remaining = new Set(known);
  while (remaining.size) {
    const ready = [...remaining].filter((k) => [...deps.get(k)].every((d) => !remaining.has(d))).sort();
    if (!ready.length) {
      const pick = [...remaining].sort()[0];
      cycles.push(pick);
      ready.push(pick);
    }
    for (const k of ready) {
      order.push(k);
      remaining.delete(k);
    }
  }
  return { order, cycles };
}

// ---------- Export queries ----------

export function exportExpr(col) {
  const c = qi(col.name);
  const type = (col.base ?? col.type).toLowerCase();
  if (col.category === 'A' || type.endsWith('[]')) return `array_to_json(${c})::text`;
  if (type === 'timestamp with time zone') return `to_char(${c} at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"Z"')`;
  if (type.startsWith('timestamp')) return `to_char(${c}, 'YYYY-MM-DD"T"HH24:MI:SS.US')`;
  if (type === 'date') return `to_char(${c}, 'YYYY-MM-DD')`;
  if (type === 'boolean') return `case when ${c} then '1' when not ${c} then '0' end`;
  if (type === 'bytea') return `encode(${c}, 'base64')`;
  return `${c}::text`;
}

export function exportQuery(t, index, total, dependsOn) {
  const cols = t.columns.filter((c) => c.generated !== 's');
  return [
    `-- ${HEADER}`,
    `-- Portable export query for ${t.schema}.${t.name}. Load order ${index} of ${total}. Depends on: ${dependsOn.length ? dependsOn.join(', ') : 'none'}.`,
    '-- Columns (source type, nullability):',
    ...cols.map((c) => `--   ${c.name} ${c.type}${c.notNull ? ' not null' : ''}`),
    '-- Output conventions: text values, ISO 8601 UTC timestamps, booleans as 1/0, bytea as base64, arrays as JSON.',
    'select',
    cols.map((c) => `  ${exportExpr(c)} as ${qi(c.name)}`).join(',\n'),
    `from ${qi(t.schema)}.${qi(t.name)}`,
    `order by ${(t.pk.length ? t.pk : [cols[0]?.name]).filter(Boolean).map(qi).join(', ') || '1'};`,
    '',
  ].join('\n');
}

// ---------- Portable types ----------

// Clean target types per engine. `keyed` columns (PK, FK, unique or indexed) need bounded text types.
export function portableTypes(col, keyed = false) {
  const t = (col.base ?? col.type).toLowerCase();
  const m = (mysql, sqlserver, sqlite, note = null) => ({ postgres: col.type, mysql, sqlserver, sqlite, note });
  let x;
  if (col.category === 'A' || t.endsWith('[]')) return m('JSON', 'NVARCHAR(MAX)', 'TEXT', 'array exported as JSON text');
  if (col.typtype === 'e') return m('VARCHAR(64)', 'NVARCHAR(64)', 'TEXT', 'enum: add CHECK with the allowed values');
  if (t === 'uuid') return m('CHAR(36)', 'UNIQUEIDENTIFIER', 'TEXT');
  if (t === 'text' || t === 'citext') return keyed ? m('VARCHAR(255)', 'NVARCHAR(450)', 'TEXT', 'bounded because the column is a key or indexed') : m('LONGTEXT', 'NVARCHAR(MAX)', 'TEXT');
  if ((x = t.match(/^character varying\((\d+)\)$/))) return m(`VARCHAR(${x[1]})`, `NVARCHAR(${x[1]})`, 'TEXT');
  if (t === 'character varying') return keyed ? m('VARCHAR(255)', 'NVARCHAR(450)', 'TEXT') : m('LONGTEXT', 'NVARCHAR(MAX)', 'TEXT');
  if ((x = t.match(/^character\((\d+)\)$/))) return m(`CHAR(${x[1]})`, `NCHAR(${x[1]})`, 'TEXT');
  if (t === 'smallint') return m('SMALLINT', 'SMALLINT', 'INTEGER');
  if (t === 'integer') return m('INT', 'INT', 'INTEGER');
  if (t === 'bigint') return m('BIGINT', 'BIGINT', 'INTEGER');
  if ((x = t.match(/^numeric\((\d+),(\d+)\)$/))) return m(`DECIMAL(${x[1]},${x[2]})`, `DECIMAL(${x[1]},${x[2]})`, 'NUMERIC');
  if (t === 'numeric') return m('DECIMAL(38,10)', 'DECIMAL(38,10)', 'NUMERIC', 'unbounded numeric: confirm precision');
  if (t === 'real') return m('FLOAT', 'REAL', 'REAL');
  if (t === 'double precision') return m('DOUBLE', 'FLOAT', 'REAL');
  if (t === 'boolean') return m('TINYINT(1)', 'BIT', 'INTEGER', 'exported as 1/0');
  if (t === 'date') return m('DATE', 'DATE', 'TEXT');
  if (t === 'timestamp with time zone') return m('DATETIME(6)', 'DATETIMEOFFSET(6)', 'TEXT', 'exported as UTC; MySQL stores it without zone');
  if (t.startsWith('timestamp')) return m('DATETIME(6)', 'DATETIME2(6)', 'TEXT');
  if (t.startsWith('time')) return m('TIME(6)', 'TIME(6)', 'TEXT');
  if (t === 'interval') return m('VARCHAR(64)', 'NVARCHAR(64)', 'TEXT', 'Postgres interval text');
  if (t === 'json' || t === 'jsonb') return m('JSON', 'NVARCHAR(MAX)', 'TEXT');
  if (t === 'bytea') return m('LONGBLOB', 'VARBINARY(MAX)', 'BLOB', 'exported as base64');
  if (t === 'inet' || t === 'cidr') return m('VARCHAR(45)', 'NVARCHAR(45)', 'TEXT');
  return m('LONGTEXT', 'NVARCHAR(MAX)', 'TEXT', `review: no direct mapping for ${col.type}`);
}

function keyedColumns(t) {
  const keyed = new Set([...t.pk, ...t.fks.flatMap((f) => f.columns)]);
  for (const ix of t.indexes) if (!ix.special) for (const c of ix.columns) keyed.add(c);
  return keyed;
}

// ---------- DBML ----------

function dbmlDefault(expr) {
  if (expr === null || expr === undefined) return null;
  let m;
  if ((m = expr.match(/^'((?:[^']|'')*)'(::[\w\s."[\]]+)?$/))) return `'${m[1].replace(/''/g, "\\'")}'`;
  if (/^-?\d+(\.\d+)?$/.test(expr)) return expr;
  if (/^(true|false)$/i.test(expr)) return expr.toLowerCase();
  return `\`${expr.replace(/`/g, "'")}\``;
}

function dbmlType(col) {
  if (col.typtype === 'e') return `${qi(col.typeSchema)}.${qi(col.typeName)}`;
  return /^[a-z0-9_]+$/i.test(col.type) ? col.type : `"${col.type.replace(/"/g, '\\"')}"`;
}

const DELETE_ACTION = { c: 'cascade', n: 'set null', d: 'set default', r: 'restrict', a: 'no action' };

export function renderDbml({ tables, enums }, order) {
  const out = [
    `// ${HEADER}`,
    '// Engine-neutral model of the application schema. Visualize at https://dbdiagram.io',
    '// Convert: npx @dbml/cli dbml2sql db/schema/schema.dbml --mysql   (or --mssql, --postgres)',
    '// Row level security, policies, functions and triggers are not represented; see db/portability/.',
    '',
    'Project app {',
    "  database_type: 'PostgreSQL'",
    "  Note: 'Generated from supabase/migrations'",
    '}',
    '',
  ];
  for (const e of enums) {
    out.push(`Enum ${qi(e.schema)}.${qi(e.name)} {`, ...e.labels.map((l) => `  ${qi(l)}`), '}', '');
  }
  const byKey = new Map(tables.map((t) => [`${t.schema}.${t.name}`, t]));
  const stubs = new Map();
  for (const k of order) {
    const t = byKey.get(k);
    out.push(`Table ${qi(t.schema)}.${qi(t.name)} {`);
    for (const c of t.columns) {
      const settings = [];
      if (t.pk.length === 1 && t.pk[0] === c.name) settings.push('pk');
      if (c.identity) settings.push('increment');
      if (c.notNull && !(t.pk.length === 1 && t.pk[0] === c.name)) settings.push('not null');
      const d = c.generated === 's' ? null : dbmlDefault(c.default);
      if (d && !c.identity) settings.push(`default: ${d}`);
      if (c.generated === 's') settings.push(`note: 'generated column: ${String(c.default ?? '').replace(/'/g, "\\'")}'`);
      out.push(`  ${qi(c.name)} ${dbmlType(c)}${settings.length ? ` [${settings.join(', ')}]` : ''}`);
    }
    const idx = [];
    if (t.pk.length > 1) idx.push(`    (${t.pk.map(qi).join(', ')}) [pk]`);
    for (const ix of t.indexes) {
      if (ix.special || !ix.columns.length) continue;
      idx.push(`    (${ix.columns.map(qi).join(', ')}) [name: '${ix.name}'${ix.unique ? ', unique' : ''}]`);
    }
    if (idx.length) out.push('', '  indexes {', ...idx, '  }');
    const notes = [t.rls ? 'RLS enabled' : 'RLS disabled', t.comment].filter(Boolean).join('. ');
    out.push(`  Note: '${notes.replace(/'/g, "\\'")}'`, '}', '');
    for (const f of t.fks) {
      const rk = `${f.refSchema}.${f.refTable}`;
      if (!byKey.has(rk)) {
        const stub = stubs.get(rk) ?? new Map();
        f.refColumns.forEach((col, i) => stub.set(col, f.refTypes?.[i] ?? 'uuid'));
        stubs.set(rk, stub);
      }
    }
  }
  for (const [rk, cols] of [...stubs].sort(([a], [b]) => a.localeCompare(b))) {
    const [s, n] = rk.split('.');
    out.push(`Table ${qi(s)}.${qi(n)} {`);
    for (const [col, type] of cols) out.push(`  ${qi(col)} ${/^[a-z0-9_]+$/i.test(type) ? type : `"${type}"`} [pk]`);
    out.push("  Note: 'Managed by Supabase (stub): recreate or map when leaving Supabase'", '}', '');
  }
  for (const k of order) {
    const t = byKey.get(k);
    for (const f of t.fks) {
      const src = f.columns.length === 1 ? qi(f.columns[0]) : `(${f.columns.map(qi).join(', ')})`;
      const dst = f.refColumns.length === 1 ? qi(f.refColumns[0]) : `(${f.refColumns.map(qi).join(', ')})`;
      const del = DELETE_ACTION[f.onDelete];
      out.push(`Ref ${qi(f.name)}: ${qi(t.schema)}.${qi(t.name)}.${src} > ${qi(f.refSchema)}.${qi(f.refTable)}.${dst}${del && del !== 'no action' ? ` [delete: ${del}]` : ''}`);
    }
  }
  out.push('');
  return out.join('\n');
}

// ---------- Portable DDL ----------

const DIALECTS = {
  mysql: {
    name: 'MySQL 8',
    q: (s) => `\`${s}\``,
    table: (s, n) => `\`${s === 'public' ? n : `${s}__${n}`}\``,
    identity: 'AUTO_INCREMENT',
    tail: ' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci',
    inlineFk: false,
  },
  sqlserver: {
    name: 'SQL Server 2019+',
    q: (s) => `[${s}]`,
    table: (s, n) => `[${s === 'public' ? 'dbo' : s}].[${n}]`,
    identity: 'IDENTITY(1,1)',
    tail: '',
    inlineFk: false,
  },
  sqlite: {
    name: 'SQLite 3',
    q: (s) => `"${s}"`,
    table: (s, n) => `"${s === 'public' ? n : `${s}__${n}`}"`,
    identity: null,
    tail: '',
    inlineFk: true,
  },
};

function literalDefault(expr) {
  if (expr === null || expr === undefined) return null;
  let m;
  if ((m = expr.match(/^'((?:[^']|'')*)'(::[\w\s."[\]]+)?$/)) && !/\[\]$/.test(m[2] ?? '')) return `'${m[1]}'`;
  if (/^-?\d+(\.\d+)?$/.test(expr)) return expr;
  return null;
}

export function renderPortableDdl({ tables, enums }, order, dialect) {
  const d = DIALECTS[dialect];
  const byKey = new Map(tables.map((t) => [`${t.schema}.${t.name}`, t]));
  const enumMap = new Map(enums.map((e) => [`${e.schema}.${e.name}`, e.labels]));
  const out = [
    `-- ${HEADER}`,
    `-- Starting-point DDL for ${d.name}, derived from the Postgres schema. REVIEW BEFORE USE.`,
    '-- Not included: row level security, policies, functions, triggers, views, extensions, grants.',
    '-- Those are listed in db/portability/supabase-dependencies.md and must be re-implemented (usually in the application).',
    '-- Tables referencing Supabase-managed tables (auth.users, storage.objects) need those tables recreated first.',
    '',
  ];
  if (dialect === 'sqlserver') {
    const schemas = [...new Set(tables.map((t) => t.schema).filter((s) => s !== 'public'))].sort();
    for (const s of schemas) out.push(`IF SCHEMA_ID('${s}') IS NULL EXEC('CREATE SCHEMA [${s}]');`);
    if (schemas.length) out.push('');
  }
  // Stub tables for Supabase-managed tables referenced by foreign keys, so the DDL runs standalone.
  const stubs = new Map();
  for (const t of tables) {
    for (const f of t.fks) {
      const rk = `${f.refSchema}.${f.refTable}`;
      if (byKey.has(rk)) continue;
      const cols = stubs.get(rk) ?? new Map();
      f.refColumns.forEach((col, i) => cols.set(col, f.refTypes?.[i] ?? 'uuid'));
      stubs.set(rk, cols);
    }
  }
  for (const [rk, cols] of [...stubs].sort(([a], [b]) => a.localeCompare(b))) {
    const [s, n] = rk.split('.');
    const defs = [...cols].map(([col, type]) => `  ${d.q(col)} ${portableTypes({ type, category: '', typtype: 'b' }, true)[dialect]} NOT NULL`);
    out.push(`-- Stub for Supabase-managed ${rk}: extend it with the data your new identity or storage provider needs.`);
    out.push(`CREATE TABLE ${d.table(s, n)} (`, [...defs, `  PRIMARY KEY (${[...cols.keys()].map(d.q).join(', ')})`].join(',\n'), `)${d.tail};`, '');
  }
  const alters = [];
  for (const k of order) {
    const t = byKey.get(k);
    const keyed = keyedColumns(t);
    const lines = [];
    const singleIntPk = t.pk.length === 1 && t.columns.find((c) => c.name === t.pk[0] && ['smallint', 'integer', 'bigint'].includes((c.base ?? c.type).toLowerCase()));
    for (const c of t.columns) {
      if (c.generated === 's') {
        lines.push(`  -- ${d.q(c.name)} generated column in Postgres: ${c.default}`);
        continue;
      }
      const pt = portableTypes(c, keyed.has(c.name))[dialect];
      const parts = [`  ${d.q(c.name)} ${pt}`];
      if (dialect === 'sqlite' && singleIntPk && c.name === t.pk[0]) {
        parts[0] = `  ${d.q(c.name)} INTEGER PRIMARY KEY${c.identity ? ' AUTOINCREMENT' : ''}`;
      } else {
        if (c.identity && d.identity && singleIntPk && c.name === t.pk[0]) parts.push(d.identity);
        if (c.notNull) parts.push('NOT NULL');
        const lit = literalDefault(c.default);
        const needsParens = dialect === 'mysql' && /^(LONGTEXT|JSON|LONGBLOB)$/.test(pt);
        if (lit && !c.identity) parts.push(`DEFAULT ${needsParens ? `(${lit})` : lit}`);
        else if (c.default && !c.identity) parts.push(`/* Postgres default: ${c.default.replace(/\*\//g, '* /')} */`);
      }
      if (c.typtype === 'e') {
        const labels = enumMap.get(`${c.typeSchema}.${c.typeName}`) ?? [];
        if (labels.length) parts.push(`CHECK (${d.q(c.name)} IN (${labels.map((l) => `'${l.replace(/'/g, "''")}'`).join(', ')}))`);
      }
      lines.push(parts.join(' '));
    }
    const constraints = [];
    if (t.pk.length && !(dialect === 'sqlite' && singleIntPk)) constraints.push(`  PRIMARY KEY (${t.pk.map(d.q).join(', ')})`);
    for (const f of t.fks) {
      const action = DELETE_ACTION[f.onDelete];
      const onDelete = action && action !== 'no action' && !(dialect === 'sqlserver' && action === 'restrict') ? ` ON DELETE ${action.toUpperCase()}` : '';
      const clause = `FOREIGN KEY (${f.columns.map(d.q).join(', ')}) REFERENCES ${d.table(f.refSchema, f.refTable)} (${f.refColumns.map(d.q).join(', ')})${onDelete}`;
      if (d.inlineFk) constraints.push(`  CONSTRAINT ${d.q(f.name)} ${clause}`);
      else alters.push(`ALTER TABLE ${d.table(t.schema, t.name)} ADD CONSTRAINT ${d.q(f.name)} ${clause};`);
    }
    const body = [...lines.filter((l) => !l.trimStart().startsWith('--')), ...constraints];
    const comments = lines.filter((l) => l.trimStart().startsWith('--'));
    out.push(`CREATE TABLE ${d.table(t.schema, t.name)} (`, ...comments, body.join(',\n'), `)${d.tail};`);
    for (const ix of t.indexes) {
      if (ix.special || !ix.columns.length) {
        out.push(`-- Index ${ix.name} uses expressions or a predicate in Postgres: ${ix.def}`);
        continue;
      }
      out.push(`CREATE ${ix.unique ? 'UNIQUE ' : ''}INDEX ${d.q(ix.name)} ON ${d.table(t.schema, t.name)} (${ix.columns.map(d.q).join(', ')});`);
    }
    out.push('');
  }
  if (alters.length) out.push('-- Foreign keys', ...alters, '');
  return out.join('\n');
}

// ---------- Supabase dependency inventory ----------

async function dependencyInventory(query, tables, root) {
  const rows = [];
  const add = (construct, where, detail, alternative) => rows.push({ construct, where, detail, alternative });

  for (const t of tables) {
    for (const fk of t.fks) {
      if (['auth', 'storage'].includes(fk.refSchema)) {
        add(`Foreign key to ${fk.refSchema}.${fk.refTable}`, `${t.schema}.${t.name}(${fk.columns.join(', ')})`, fk.name,
          fk.refSchema === 'auth' ? 'Own users table synced from the new identity provider; keep the same UUIDs.' : 'Own files table plus S3-compatible object storage.');
      }
    }
  }
  const policies = await query(`
    select schemaname as schema, tablename as table, policyname as name, cmd, roles::text as roles,
           coalesce(qual, '') as qual, coalesce(with_check, '') as with_check
    from pg_policies order by schemaname, tablename, policyname`);
  for (const p of policies) {
    const expr = `${p.qual} ${p.with_check}`;
    const fns = ['auth.uid()', 'auth.jwt()', 'auth.role()', 'auth.email()'].filter((f) => expr.includes(f));
    const roles = String(p.roles).replace(/[{}"]/g, '').split(',').filter((r) => ['anon', 'authenticated', 'service_role'].includes(r));
    if (p.schema === 'storage') {
      add('Storage policy', `storage.${p.table}`, `${p.name} (${p.cmd})`, 'Authorize file access in the application or with signed URLs of the new storage.');
    } else if (new RegExp(MANAGED_REGEX).test(p.schema)) {
      continue;
    } else if (fns.length) {
      add('RLS policy using Supabase auth helpers', `${p.schema}.${p.table}`, `${p.name} (${p.cmd}) uses ${fns.join(', ')}`,
        "Postgres: RLS with current_setting('app.user_id') set per request. Other engines: the DAL authorization checks.");
    } else if (roles.length) {
      add('RLS policy for Supabase roles', `${p.schema}.${p.table}`, `${p.name} (${p.cmd}) to ${roles.join(', ')}`, 'Map anon/authenticated to application roles, or rely on DAL checks.');
    }
  }
  const functions = await query(`
    select n.nspname as schema, p.proname as name, p.prosecdef as definer,
           (pg_get_functiondef(p.oid) ~ 'auth\\.') as uses_auth
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname !~ '${MANAGED_REGEX}' and p.prokind in ('f', 'p')
      and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
    order by 1, 2`);
  for (const f of functions) {
    if (yes(f.definer) || yes(f.uses_auth)) {
      add('Database function', `${f.schema}.${f.name}`, [yes(f.definer) ? 'security definer' : '', yes(f.uses_auth) ? 'references auth schema' : ''].filter(Boolean).join(', '),
        'Postgres: keep. Other engines: re-implement in application services.');
    }
  }
  const triggers = await query(`
    select n.nspname as schema, c.relname as table, tg.tgname as name, pn.nspname || '.' || p.proname as function
    from pg_trigger tg
    join pg_class c on c.oid = tg.tgrelid join pg_namespace n on n.oid = c.relnamespace
    join pg_proc p on p.oid = tg.tgfoid join pg_namespace pn on pn.oid = p.pronamespace
    where not tg.tgisinternal and n.nspname in ('auth', 'storage') and pn.nspname !~ '${MANAGED_REGEX}'
    order by 1, 2, 3`);
  for (const t of triggers) {
    add('Trigger on Supabase-managed table', `${t.schema}.${t.table}`, `${t.name} -> ${t.function}`, 'Run the same logic from the application after sign-up or upload.');
  }
  const pubs = await query(`select pubname, schemaname, tablename from pg_publication_tables where schemaname !~ '${MANAGED_REGEX}' order by 1, 2, 3`);
  for (const p of pubs) add('Realtime publication', `${p.schemaname}.${p.tablename}`, p.pubname, 'Logical replication, LISTEN/NOTIFY or an application event bus.');
  const grants = await query(`
    select grantee, table_schema as schema, count(*)::int as n
    from information_schema.role_table_grants
    where grantee in ('anon', 'authenticated', 'service_role') and table_schema !~ '${MANAGED_REGEX}'
    group by 1, 2 order by 1, 2`);
  for (const g of grants) add('Table privileges for Supabase role', `${g.schema}.*`, `${g.n} grants to ${g.grantee}`, 'Recreate equivalent roles and grants, or connect as one application role.');
  const optional = (await query(`select to_regclass('storage.buckets') is not null as storage, to_regclass('cron.job') is not null as cron, to_regclass('vault.secrets') is not null as vault`))[0] ?? {};
  if (yes(optional.storage)) {
    for (const b of await query(`select id, public from storage.buckets order by id`)) {
      add('Storage bucket', `storage.buckets/${b.id}`, yes(b.public) ? 'public' : 'private', 'S3-compatible bucket with equivalent access rules.');
    }
  }
  if (yes(optional.cron)) {
    for (const j of await query(`select jobname, schedule from cron.job order by jobname`)) add('pg_cron job', `cron.job/${j.jobname}`, j.schedule, 'Vercel Cron or the scheduler of the new platform.');
  }
  if (yes(optional.vault)) {
    const n = Number((await query(`select count(*)::int as n from vault.secrets`))[0]?.n ?? 0);
    if (n > 0) add('Vault secrets', 'vault.secrets', `${n} secrets`, 'Secret manager of the new platform.');
  }
  const extensions = await query(`
    select e.extname as name, n.nspname as schema from pg_extension e join pg_namespace n on n.oid = e.extnamespace
    where e.extname <> 'plpgsql' order by 1`);
  const fnDir = path.join(root, 'supabase', 'functions');
  const edge = fs.existsSync(fnDir)
    ? fs.readdirSync(fnDir, { withFileTypes: true }).filter((x) => x.isDirectory() && !x.name.startsWith('_') && !x.name.startsWith('.')).map((x) => x.name).sort()
    : [];
  for (const e of edge) add('Edge Function', `supabase/functions/${e}`, 'Deno runtime', 'Vercel Function or a Node service.');
  return { rows, extensions };
}

function renderInventory({ rows, extensions }) {
  const lines = [
    `<!-- ${HEADER} -->`,
    '# Supabase dependency inventory',
    '',
    'Constructs that tie the database or the app to Supabase. Each needs a replacement when moving to another SQL service or platform. See `db/PORTABILITY.md`.',
    '',
  ];
  if (!rows.length) {
    lines.push('No Supabase-specific constructs found in application schemas.', '');
  } else {
    lines.push('| Construct | Where | Detail | Portable replacement |', '|---|---|---|---|');
    for (const r of rows) lines.push(`| ${r.construct} | \`${r.where}\` | ${r.detail} | ${r.alternative} |`);
    lines.push('');
  }
  lines.push('## Installed extensions', '', 'Extensions present in the database (many are Supabase platform defaults). Only those used by application objects need a plan.', '');
  lines.push(extensions.length ? extensions.map((e) => `- \`${e.name}\` (schema \`${e.schema}\`)`).join('\n') : '- none');
  lines.push('');
  return lines.join('\n');
}

// ---------- Main ----------

function writeFile(root, rel, content) {
  const abs = path.join(root, rel);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, content, 'utf8');
}

export async function generate({ root, query }) {
  const catalog = await loadCatalog(query);
  const { tables } = catalog;
  const { order, cycles } = loadOrder(tables);
  const byKey = new Map(tables.map((t) => [`${t.schema}.${t.name}`, t]));

  const qdir = path.join(root, 'db', 'export', 'queries');
  fs.mkdirSync(qdir, { recursive: true });
  for (const f of fs.readdirSync(qdir)) if (/^\d{3}_.+\.sql$/.test(f)) fs.rmSync(path.join(qdir, f));

  const manifestTables = [];
  order.forEach((k, i) => {
    const t = byKey.get(k);
    const idx = String(i + 1).padStart(3, '0');
    const dependsOn = [...new Set(t.fks.map((f) => `${f.refSchema}.${f.refTable}`))].filter((d) => d !== k).sort();
    const file = `${idx}_${t.schema}.${t.name}.sql`;
    fs.writeFileSync(path.join(qdir, file), exportQuery(t, i + 1, order.length, dependsOn), 'utf8');
    const keyed = keyedColumns(t);
    manifestTables.push({
      order: i + 1,
      schema: t.schema,
      table: t.name,
      query: `queries/${file}`,
      rowLevelSecurity: t.rls,
      primaryKey: t.pk,
      dependsOn,
      foreignKeys: t.fks.map((f) => ({ name: f.name, columns: f.columns, references: `${f.refSchema}.${f.refTable}`, refColumns: f.refColumns })),
      columns: t.columns
        .filter((c) => c.generated !== 's')
        .map((c) => ({ name: c.name, sourceType: c.type, nullable: !c.notNull, identity: Boolean(c.identity), default: c.default ?? null, portableTypes: portableTypes(c, keyed.has(c.name)) })),
    });
  });
  const manifest = {
    generatedBy: 'pnpm db:sync (scripts/db/lib/generate-artifacts.mjs)',
    csv: {
      format: 'RFC 4180, UTF-8, header row',
      null: 'unquoted empty field',
      emptyString: 'quoted empty field ""',
      timestamps: 'ISO 8601; timestamptz converted to UTC with Z suffix',
      boolean: '1 or 0',
      bytea: 'base64',
      arrays: 'JSON array text',
      json: 'JSON text',
    },
    loadOrderCycles: cycles,
    tables: manifestTables,
  };
  writeFile(root, 'db/export/manifest.json', `${JSON.stringify(manifest, null, 2)}\n`);
  writeFile(root, 'db/schema/schema.dbml', renderDbml(catalog, order));
  for (const dialect of Object.keys(DIALECTS)) writeFile(root, `db/schema/portable/${dialect}.sql`, renderPortableDdl(catalog, order, dialect));
  const inventory = await dependencyInventory(query, tables, root);
  writeFile(root, 'db/portability/supabase-dependencies.md', renderInventory(inventory));
  return { tables: order.length, cycles, dependencies: inventory.rows.length };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { root, dbUrl } = cliArgs();
  if (!dbUrl) {
    console.error('Pass --db-url <postgres url>, or run pnpm db:sync to build the artifacts from supabase/migrations.');
    process.exit(2);
  }
  try {
    const res = await generate({ root, query: makeRunner(root, dbUrl) });
    console.log(
      `db artifacts: ${res.tables} tables${res.cycles.length ? ` (FK cycles broken at: ${res.cycles.join(', ')})` : ''}, ` +
        `${res.dependencies} Supabase-specific constructs inventoried`,
    );
  } catch (err) {
    console.error(`generate-artifacts failed: ${err.message}`);
    process.exit(1);
  }
}
